export type MessageKey = keyof typeof messages[typeof DEFAULT_LANGUAGE];

function fill(template: string, params?: TranslateParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => String(params[key] ?? `{${key}}`));
}

export function translate(language: Language, key: MessageKey, params?: TranslateParams): string {
  return fill(messages[language]?.[key] ?? messages[DEFAULT_LANGUAGE][key], params);
}

/** Resolve the active UI language from persisted desktop settings. */
export function useLanguage(): Language {
  return useAppStore((s) => s.desktopSettings?.language ?? DEFAULT_LANGUAGE);
}

/** Reactive translator bound to the active language. */
export function useT(): (key: MessageKey, params?: TranslateParams) => string {
  const language = useLanguage();
  return React.useCallback((key: MessageKey, params?: TranslateParams) => translate(language, key, params), [language]);
}
